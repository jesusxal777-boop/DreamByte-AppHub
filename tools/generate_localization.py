#!/usr/bin/env python3
"""Generates the typed L10nKey enum and validates translation files.

Source of truth: Core/Sources/AppHubCore/Resources/Localization/<lang>.json
Run from the repository root: python3 tools/generate_localization.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LOCALIZATION = ROOT / "Core/Sources/AppHubCore/Resources/Localization"
OUTPUT = ROOT / "Core/Sources/AppHubCore/Localization/L10nKey.swift"
LANGUAGES = ["es", "en", "fr", "pt"]


def case_name(key: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", key)
    first, *rest = [p for p in parts if p]
    return first[:1].lower() + first[1:] + "".join(p[:1].upper() + p[1:] for p in rest)


def main() -> int:
    catalogs = {}
    for lang in LANGUAGES:
        path = LOCALIZATION / f"{lang}.json"
        if not path.exists():
            print(f"missing translation file: {path}", file=sys.stderr)
            return 1
        with path.open(encoding="utf-8") as handle:
            catalogs[lang] = json.load(handle)

    base = catalogs["es"]
    problems = []
    for lang, catalog in catalogs.items():
        missing = sorted(set(base) - set(catalog))
        extra = sorted(set(catalog) - set(base))
        empty = sorted(k for k, v in catalog.items() if not str(v).strip())
        if missing:
            problems.append(f"{lang}: missing {missing}")
        if extra:
            problems.append(f"{lang}: extra {extra}")
        if empty:
            problems.append(f"{lang}: empty {empty}")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1

    names = {}
    for key in sorted(base):
        name = case_name(key)
        if name in names:
            print(f"duplicate Swift case {name}: {names[name]} / {key}", file=sys.stderr)
            return 1
        names[name] = key

    lines = [
        "// Generated by tools/generate_localization.py. Do not edit by hand.",
        "import Foundation",
        "",
        "public enum L10nKey: String, CaseIterable, Sendable {",
    ]
    for key in sorted(base):
        lines.append(f'    case {case_name(key)} = "{key}"')
    lines.append("}")
    lines.append("")
    content = "\n".join(lines)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)

    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(
                "L10nKey.swift is out of date; run python3 tools/generate_localization.py",
                file=sys.stderr,
            )
            return 1
        print(f"ok: {OUTPUT.relative_to(ROOT)} matches {len(base)} keys across {len(LANGUAGES)} languages")
        return 0

    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} with {len(base)} keys across {len(LANGUAGES)} languages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
